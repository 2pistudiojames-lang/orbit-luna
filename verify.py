from playwright.sync_api import sync_playwright
import json, pathlib, time
ROOT=pathlib.Path('C:/AI/hermesSite/THRESSJS')
results={'checks':[], 'errors':[], 'failed_requests':[]}
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='C:/AI/hermesBrowser/App/Chrome-bin/chrome.exe',headless=True,args=['--enable-webgl','--ignore-gpu-blocklist'])
    page=browser.new_page(viewport={'width':1440,'height':900},device_scale_factor=1)
    page.on('pageerror',lambda e: results['errors'].append(str(e)))
    page.on('requestfailed',lambda r: results['failed_requests'].append(r.url))
    page.goto('http://127.0.0.1:8788/',wait_until='networkidle')
    page.wait_for_function('window.__orbit?.ready === true',timeout=30000)
    page.wait_for_selector('#loading',state='detached')
    def state(): return page.evaluate('window.__orbit.getState()')
    def check(name,condition):
        assert condition,name
        results['checks'].append(name)
    check('WebGL rendering active',state()['drawCalls']>0)
    start=state()['day'];page.wait_for_timeout(350);check('Simulation advances',state()['day']>start)
    page.click('#play');start=state()['day'];page.wait_for_timeout(250);check('Pause stops time',state()['day']==start)
    page.select_option('#speed','10');check('Speed control',state()['speed']==10)
    page.locator('#time').fill('14');check('Timeline seek',abs(state()['day']-14)<.01)
    page.locator('#orbits').uncheck();check('Orbit toggle',not state()['orbits']);page.locator('#orbits').check()
    page.locator('#labels').uncheck();check('Label toggle',not state()['labels']);page.locator('#labels').check()
    page.locator('#clouds').uncheck();check('Cloud toggle',not state()['clouds']);page.locator('#clouds').check()
    for view in ['solar','moon','earth']:
        page.click('[data-view="'+view+'"]');page.wait_for_timeout(1250);check('Camera view: '+view,state()['view']==view)
        page.screenshot(path=str(ROOT/('screenshot-'+view+'.png')))
    page.click('#restart');check('Reset timeline',state()['day']==0)
    page.mouse.move(700,440);page.mouse.down();page.mouse.move(850,450,steps=12);page.mouse.up();page.mouse.wheel(0,100);page.wait_for_timeout(350)
    check('OrbitControls remains rendering after drag and zoom',state()['drawCalls']>0)
    page.click('#reset');page.wait_for_timeout(1300)
    page.click('#infoBtn');check('About dialog opens',page.locator('#info').evaluate('(el)=>el.open'));page.click('#info .close')
    page.select_option('#speed','0.5')
    page.screenshot(path=str(ROOT/'screenshot-desktop.png'))
    page.set_viewport_size({'width':390,'height':844});page.click('#reset');page.wait_for_timeout(1400)
    check('Mobile has no horizontal overflow',page.evaluate('document.documentElement.scrollWidth <= innerWidth'))
    page.screenshot(path=str(ROOT/'screenshot-mobile.png'),full_page=True)
    check('No JavaScript errors',not results['errors'])
    check('No failed requests',not results['failed_requests'])
    results['final_state']=state()
    results['webgl']=page.evaluate("(()=>{const gl=document.querySelector('#space canvas').getContext('webgl2');return {version:gl.getParameter(gl.VERSION),renderer:gl.getParameter(gl.RENDERER)}})()")
    browser.close()
(ROOT/'test-results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps(results,ensure_ascii=False,indent=2))
